"""Turn the exported icon data into one SVG per icon plus a sprite and a JSON map."""
import json, re, sys, pathlib
src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
icons = {}
for k, v in json.loads((src / "batch1.json").read_text()).items():
    icons[k] = v
for f in sorted(src.glob("batch*.txt")):
    for line in f.read_text().splitlines():
        if "=" not in line: continue
        name, data = line.split("=", 1)
        paths = []
        for d in data.split("|"):
            if d.startswith("E"):
                paths.append(f'<path fill-rule="evenodd" clip-rule="evenodd" d="{d[1:]}" fill="currentColor"/>')
            else:
                paths.append(f'<path d="{d}" fill="currentColor"/>')
        icons[name] = "".join(paths)
icons = dict(sorted(icons.items()))
(out / "svg").mkdir(parents=True, exist_ok=True)
for name, body in icons.items():
    (out / "svg" / f"{name}.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" aria-hidden="true">{body}</svg>\n')
sprite = "".join(f'<symbol id="ads-icon-{n}" viewBox="0 0 24 24">{b}</symbol>' for n, b in icons.items())
(out / "sprite.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" style="display:none">{sprite}</svg>\n')
(out / "icons.json").write_text(json.dumps(icons, indent=0))
print(len(icons), "icons")

# CSS mask classes: <span class="ads-icon ads-icon--train"></span> inherits currentColor.
from urllib.parse import quote
css = ["/* ADS icons as CSS masks. Generated by scripts/build-icons.py. */",
       ".ads-icon{display:inline-block;flex:none;width:var(--ads-size-icon-md,24px);height:var(--ads-size-icon-md,24px);background-color:currentColor;-webkit-mask:var(--ads-icon) center/contain no-repeat;mask:var(--ads-icon) center/contain no-repeat;vertical-align:middle}",
       ".ads-icon--sm{width:var(--ads-size-icon-sm,16px);height:var(--ads-size-icon-sm,16px)}",
       ".ads-icon--lg{width:var(--ads-size-icon-lg,32px);height:var(--ads-size-icon-lg,32px)}"]
for n, b in icons.items():
    svg = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'>{b.replace(chr(34), chr(39))}</svg>"
    enc = quote(svg, safe=" '=/:.,-")
    css.append('.ads-icon--%s{--ads-icon:url("data:image/svg+xml,%s")}' % (n, enc))
(out.parent / "css" / "icons.css").write_text("\n".join(css) + "\n")
print("wrote css/icons.css")

# Glyphs referenced directly by components.css (checkbox, radio, selected list row).
glyphs = ["checkbox-unselected", "checkbox-selected", "checkbox-partial", "radio-unselected", "radio-selected", "check-circle"]
root_vars = []
for n in glyphs:
    svg = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'>{icons[n].replace(chr(34), chr(39))}</svg>"
    root_vars.append('--ads-glyph-%s:url("data:image/svg+xml,%s");' % (n, quote(svg, safe=" '=/:.,-")))
with open(out.parent / "css" / "icons.css", "a") as f:
    f.write(":root{" + "".join(root_vars) + "}\n")
