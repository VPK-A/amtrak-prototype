"""Build css/tokens.css, dist/tokens.js and dist/tokens.resolved.json from tokens/tokens.json.

Run from the repo root:  python3 scripts/build-tokens.py
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((root / "tokens/tokens.json").read_text())
prim = T["primitive"]["color"]

def slug(s): return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
def ref_var(ref):
    group, step = ref.strip("{}").split("/")
    return f"var(--ads-color-{group}-{step})"
def ref_val(ref):
    group, step = ref.strip("{}").split("/")
    return prim[group][step]
def px(n): return f"{n}px" if isinstance(n, (int, float)) and n != 0 else "0"

L, D, resolved = [], [], {"light": {}, "dark": {}}
out = ["/* ADS Next tokens. Generated by scripts/build-tokens.py. Do not edit by hand. */", ":root {"]

out.append("  /* Primitive colors */")
for g, steps in prim.items():
    for s, v in steps.items():
        out.append(f"  --ads-color-{g}-{s}: {v};")

out.append("  /* Spacing, radius, sizing */")
for k, v in T["space"].items():  out.append(f"  --ads-space-{k}: {px(v)};")
for k, v in T["radius"].items(): out.append(f"  --ads-radius-{k}: {px(v)};")
for k, v in T["size"].items():   out.append(f"  --ads-size-{k}: {px(v)};")

ty = T["typography"]
out.append("  /* Typography */")
out.append(f"  --ads-font-family: {ty['family']['web']};")
for k, v in ty["weight"].items(): out.append(f"  --ads-font-weight-{k}: {v};")

def type_vars(styles, indent="  "):
    lines = []
    for name, spec in styles.items():
        if name.startswith("$"): continue
        size, lh, ls, w = spec
        lines.append(f"{indent}--ads-type-{name}-size: {size}px;")
        lines.append(f"{indent}--ads-type-{name}-line-height: {lh};")
        lines.append(f"{indent}--ads-type-{name}-letter-spacing: {ls};")
        lines.append(f"{indent}--ads-type-{name}-weight: var(--ads-font-weight-{w});")
    return lines
out += type_vars(ty["web-desktop"])

lay = T["layout"]
out.append("  /* Layout (web grid: mobile values; overridden at breakpoints below) */")
out.append(f"  --ads-grid-columns: {lay['grid']['mobile']['columns']};")
out.append(f"  --ads-grid-gutter: var(--ads-space-16);")
out.append(f"  --ads-grid-margin: var(--ads-space-16);")
out.append(f"  --ads-content-max: {lay['grid']['desktop']['maxContent']}px;")
out.append(f"  --ads-reading-measure: {lay['readingMeasure']}px;")

out.append("  /* Motion & focus (from component specs) */")
out.append("  --ads-focus-ring-width: 2px;")
out.append("  --ads-focus-ring-offset: 2px;")
out.append("  --ads-duration-fast: 120ms;")
out.append("  --ads-duration-base: 200ms;")
out.append("  --ads-ease: cubic-bezier(0.2, 0, 0, 1);")

out.append("  /* Semantic colors: light */")
for name, pair in T["semantic"]["color"].items():
    if name.startswith("$"): continue
    l, d = pair
    v = f"--ads-{slug(name)}"
    L.append(f"  {v}: {ref_var(l)};")
    D.append(f"  {v}: {ref_var(d)};")
    resolved["light"][name], resolved["dark"][name] = ref_val(l), ref_val(d)
out += L
for name, pair in T["semantic"]["shadow"].items():
    if name.startswith("$"): continue
    l, d = pair
    out.append(f"  --ads-shadow-{name}: 0 {l[0]}px {l[1]}px 0 {ref_var(l[2])};")
    D.append(f"  --ads-shadow-{name}: 0 {d[0]}px {d[1]}px 0 {ref_var(d[2])};")
out.append("  color-scheme: light;")
out.append("}")

dark = "\n".join(D + ["  color-scheme: dark;"])
out.append("\n/* Dark mode: follows the OS unless a page forces data-theme=\"light\" */")
out.append("@media (prefers-color-scheme: dark) {\n:root:not([data-theme=\"light\"]) {\n" + dark + "\n}\n}")
out.append(":root[data-theme=\"dark\"], [data-theme=\"dark\"] {\n" + dark + "\n}")
out.append(":root[data-theme=\"light\"], [data-theme=\"light\"] { color-scheme: light; }")

out.append("\n/* Web mobile type tier: below 640px only Display, H1 and H2 change */")
out.append("@media (max-width: 639px) {\n:root:not([data-platform]) {\n" + "\n".join(type_vars(ty["web-mobile"])) + "\n}\n}")
out.append(f"@media (min-width: {lay['breakpoints']['tablet']}px) {{\n:root {{ --ads-grid-columns: 8; --ads-grid-gutter: var(--ads-space-24); --ads-grid-margin: var(--ads-space-32); }}\n}}")
out.append(f"@media (min-width: {lay['breakpoints']['desktop']}px) {{\n:root {{ --ads-grid-columns: 12; }}\n}}")

for plat in ("ios", "android"):
    n = lay["native"][f"{plat}-phone"]
    out.append(f"\n/* Native layer: {plat}. Put data-platform=\"{plat}\" on <html> in a web view or native-styled prototype. */")
    out.append(f"[data-platform=\"{plat}\"] {{\n  --ads-font-family: {ty['family'][plat]};\n  --ads-grid-columns: 1;\n  --ads-grid-gutter: 0px;\n  --ads-grid-margin: {n['margin']}px;\n" + "\n".join(type_vars(ty[plat])) + "\n}")

(root / "css/tokens.css").write_text("\n".join(out) + "\n")

dist = root / "dist"; dist.mkdir(exist_ok=True)
flat = {
    "color": resolved, "primitive": prim, "space": T["space"], "radius": T["radius"], "size": T["size"],
    "typography": ty, "layout": lay,
    "shadow": {k: v for k, v in T["semantic"]["shadow"].items() if not k.startswith("$")},
}
(dist / "tokens.resolved.json").write_text(json.dumps(flat, indent=2))
(dist / "tokens.js").write_text("// Generated by scripts/build-tokens.py\nexport const tokens = " + json.dumps(flat, indent=2) + ";\nexport default tokens;\n")
print("wrote css/tokens.css,", len(L), "semantic colors")
